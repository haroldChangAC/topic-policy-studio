"""Audit version-4 to version-5 conversion on the real six-report project."""
import hashlib
import io
import json
import time
import zipfile
from pathlib import Path

import pandas as pd
from openpyxl import load_workbook
from studio.annual import calculate,group_key
from studio.annual_heatmap import ALL
from studio.grouped_charts import cells,for_scope,source
from studio.policy_project import open_policy_project,save_policy_project
from studio.policy_transfer import apply_transfer,plan_transfer
from studio.project import open_project,save_project
from studio.runtime import ROOT
from studio.workflow import csv_bytes,excel_bytes

out=ROOT/'outputs/project_compact_validation';out.mkdir(parents=True,exist_ok=True)
source_path=ROOT/'outputs/real_policy_2022_2024/real_policy_grouped.hpts.zip'
source_raw=source_path.read_bytes();source_hash=hashlib.sha256(source_raw).hexdigest()
start=time.perf_counter();before=open_project(source_raw);print('读取旧项目',len(before['rows']),len(before['segments']),flush=True)
raw=save_project(before);newpath=out/'real_policy_grouped_v5.hpts.zip';newpath.write_bytes(raw)
after=open_project(raw);print('版本 5 保存重开',len(raw),flush=True)
assert before['project_info']['version']==4 and after['project_info']['version']==5
assert source_hash==hashlib.sha256(source_path.read_bytes()).hexdigest()
for key in ('rows','segments','topics'):
    a=json.loads(before[key].to_json(orient='split',force_ascii=False,double_precision=15))
    b=json.loads(after[key].to_json(orient='split',force_ascii=False,double_precision=15))
    assert a['columns']==b['columns'] and a['data']==b['data'],key
assert before['metadata']==after['metadata'] and before['topic_edits']==after['topic_edits']
assert before['visualization']==after['visualization']
f=before['metadata']['generated_fields'];lookup=after['rows'].set_index(f['document_id'])
for _,part in after['segments'].iterrows():
    parent=lookup.loc[part[f['document_id']]];a=int(part[f['start_char']]);b=int(part[f['end_char']])
    assert parent[f['original_text']][a:b]==part[f['segment_text']]
    assert all(part[col]==parent[col] for col in after['metadata']['original_columns'])
settings=after['visualization']['annual_panel']
pd.testing.assert_frame_equal(calculate(before,settings)[1],calculate(after,settings)[1])
d,p,s,m=source(before,settings);d2,p2,s2,m2=source(after,settings)
pd.testing.assert_frame_equal(p,p2);assert m==m2
vis=after['visualization']['grouped_annual_charts']
for mode in ('line','heat'):
    cfg=vis[mode]
    for scope in cfg['scopes']:
        frame=cells(for_scope(before,d,p,s,m,scope),cfg['metric'],cfg['years'],cfg['topics'],settings,m)
        frame2=cells(for_scope(after,d2,p2,s2,m2,scope),cfg['metric'],cfg['years'],cfg['topics'],settings,m2)
        pd.testing.assert_frame_equal(frame,frame2)
print('原始和归组年度图输入一致',flush=True)
# CSV and Excel are regenerated by the existing production export functions.
record_csv=csv_bytes(after['rows']);segment_csv=csv_bytes(after['segments'])
(out/'records.csv').write_bytes(record_csv);(out/'segments.csv').write_bytes(segment_csv)
for name,data in [('rows',record_csv),('segments',segment_csv)]:
    frame=pd.read_csv(io.BytesIO(data),dtype=str,keep_default_na=False)
    columns=after['metadata']['original_columns']+[f['document_id'],f['original_text']]
    if name=='segments':columns += [f['segment_id'],f['segment_order'],f['start_char'],f['end_char'],f['segment_text'],f['topic_id']]
    for col in columns:
        assert frame[col].tolist()==after[name][col].astype(str).tolist(),(name,col)
print('CSV 逐列回读通过',flush=True)
excel=excel_bytes(after);(out/'results.xlsx').write_bytes(excel)
book=load_workbook(io.BytesIO(excel),read_only=True,data_only=False)
for name,frame in [('records',after['rows']),('segments',after['segments'])]:
    itr=book[name].values;headers=list(next(itr));cols=after['metadata']['original_columns']+[f['document_id'],f['original_text']]
    if name=='segments':cols += [f['segment_id'],f['segment_order'],f['start_char'],f['end_char'],f['segment_text'],f['topic_id']]
    count=0
    for i,values in enumerate(itr):
        count+=1
        for col in cols:
            actual=values[headers.index(col)];expected=frame.iloc[i][col]
            assert (actual==expected) or (actual is None and expected==''),(name,i,col)
    assert count==len(frame)
book.close();print('Excel 文档和片段逐列回读通过',flush=True)
# Transfer one reconstructed entire document through production policy workflow.
first=after['rows'].iloc[0];docid=first[f['document_id']]
plan=plan_transfer(after,hashlib.sha256(raw).hexdigest(),[docid],{'title':'标题','date':'官网刊载日期','region':'分组','source':'来源网址'})
policy=apply_transfer(plan);policy_raw=save_policy_project(policy);policy2=open_policy_project(policy_raw)
assert policy2['policies'][0]['original_text']==first[f['original_text']]
assert policy2['policies'][0]['original_fields']=={col:first[col] for col in after['metadata']['original_columns']}
assert len(policy2['policies'][0]['theme_origin']['segments'])==int(after['segments'][f['document_id']].eq(docid).sum())
(out/'transferred_sample.pmc.zip').write_bytes(policy_raw)
assert open_project(save_project(after))['visualization']==after['visualization']
print('政策转入与再次保存通过',flush=True)
def sizes(blob):
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        return {x.filename:{'uncompressed':x.file_size,'compressed':x.compress_size} for x in archive.infolist()}
old_sizes=sizes(source_raw);new_sizes=sizes(raw)
summary={'source_version':4,'new_version':5,'source_file':str(source_path.relative_to(ROOT)),
         'source_sha256':source_hash,'source_unchanged':True,'output_file':str(newpath.relative_to(ROOT)),
         'old_zip_bytes':len(source_raw),'new_zip_bytes':len(raw),'reduction_percent':(1-len(raw)/len(source_raw))*100,
         'old_entries':old_sizes,'new_entries':new_sizes,'documents':len(after['rows']),'segments':len(after['segments']),
         'verified':['所有文档和片段字段、列顺序和主题表逐项相等','片段全文与原文位置一致','运行参数、主题名称、人工归组与图表设置相等',
                     '原始及归组年度面板与图表输入一致','CSV 和 Excel 的文档/片段字段逐项回读','政策材料转入并重新打开','新项目再次另存重开'],
         'excel_bytes':len(excel),'csv_records_bytes':len(record_csv),'csv_segments_bytes':len(segment_csv),
         'elapsed_seconds':round(time.perf_counter()-start,2)}
(out/'summary.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(json.dumps(summary,ensure_ascii=False,indent=2),flush=True)
